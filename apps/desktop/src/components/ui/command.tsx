/**
 * A command palette in a dialog.
 *
 * The header is inside the content, which is where Radix looks for it: hoisted
 * out, as shadcn ships it, the title and description were never associated
 * with the dialog at all and it announced itself as unnamed. It stays
 * `sr-only` — the input already says what this is on screen.
 *
 * No close button by default either. It landed in the top-right corner *over
 * the search field*, so the palette opened with a control sitting on the text
 * being typed; Escape and clicking away both still close it.
 */
function CommandDialog({
  title = "Command Palette",
  description = "Search for a command to run...",
  children,
  className,
  showCloseButton = false,
  ...props
}: React.ComponentProps<typeof Dialog> & {
  title?: string
  description?: string
  className?: string
  showCloseButton?: boolean
}) {
  return (
    <Dialog {...props}>
      <DialogContent
        className={cn("overflow-hidden p-0", className)}
        showCloseButton={showCloseButton}
      >
        <DialogHeader className="sr-only">
          <DialogTitle>{title}</DialogTitle>
          <DialogDescription>{description}</DialogDescription>
        </DialogHeader>
        {/*
          The app's own density, not the demo's. shadcn's palette is sized for
          a marketing screenshot — 48px input, 12px of padding per row — which
          in a 13px application meant five results where a dozen fit, on the
          one screen whose entire job is showing you a list to pick from.
        */}
        <Command className="**:data-[slot=command-input-wrapper]:h-10 [&_[cmdk-group-heading]]:px-2 [&_[cmdk-group-heading]]:font-medium [&_[cmdk-group-heading]]:text-muted-foreground [&_[cmdk-group]]:px-2 [&_[cmdk-group]:not([hidden])_~[cmdk-group]]:pt-0 [&_[cmdk-input-wrapper]_svg]:h-4 [&_[cmdk-input-wrapper]_svg]:w-4 [&_[cmdk-input]]:h-10 [&_[cmdk-item]]:px-2 [&_[cmdk-item]]:py-1.5 [&_[cmdk-item]_svg]:h-4 [&_[cmdk-item]_svg]:w-4">
          {children}
        </Command>
      </DialogContent>
    </Dialog>
  )
}

